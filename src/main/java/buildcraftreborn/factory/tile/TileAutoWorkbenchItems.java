package buildcraftreborn.factory.tile;

import net.minecraft.core.BlockPos;
import net.minecraft.network.chat.Component;
import net.minecraft.world.InteractionHand;
import net.minecraft.world.MenuProvider;
import net.minecraft.world.entity.player.Inventory;
import net.minecraft.world.entity.player.Player;
import net.minecraft.world.inventory.AbstractContainerMenu;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.level.block.state.BlockState;

import buildcraftreborn.factory.BCFactoryBlocks;
import buildcraftreborn.factory.container.ContainerAutoCraftItems;

/** The auto workbench: a 3x3 crafting grid. */
public class TileAutoWorkbenchItems extends TileAutoWorkbenchBase implements MenuProvider {
    public TileAutoWorkbenchItems(BlockPos pos, BlockState state) {
        super(BCFactoryBlocks.AUTO_WORKBENCH_ITEMS_TILE.get(), pos, state, 3, 3);
    }

    @Override
    public boolean onActivated(Player player, InteractionHand hand, ItemStack held) {
        if (!level.isClientSide) {
            openGui(player);
        }
        return true;
    }

    @Override
    public Component getDisplayName() {
        return Component.translatable(getBlockState().getBlock().getDescriptionId());
    }

    @Override
    public AbstractContainerMenu createMenu(int windowId, Inventory inventory, Player player) {
        return new ContainerAutoCraftItems(windowId, player, this);
    }
}
