package buildcraftreborn.lib.fluid;

import java.util.Optional;

import com.mojang.serialization.Codec;
import com.mojang.serialization.codecs.RecordCodecBuilder;

import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.tags.FluidTags;
import net.minecraft.tags.TagKey;
import net.minecraft.util.ExtraCodecs;
import net.minecraft.world.item.Item;
import net.minecraft.world.level.material.Fluid;

import net.neoforged.neoforge.fluids.FluidStack;
import net.neoforged.neoforge.registries.datamaps.AdvancedDataMapType;
import net.neoforged.neoforge.registries.datamaps.DataMapType;
import net.neoforged.neoforge.registries.datamaps.DataMapValueMerger;
import net.neoforged.neoforge.registries.datamaps.RegisterDataMapTypesEvent;

import buildcraftreborn.BuildCraftReborn;

/** Data maps for combustion engine fuels and coolants. These replace 1.12's code-registered fuel and coolant lists
 * ({@code BCEnergyRecipes}), so data packs can change them. The built-in values are generated by
 * {@code BCDataMapsProvider} from 1.12's numbers.
 * <ul>
 * <li>{@code data/<namespace>/data_maps/fluid/fuels.json}: {@code power_per_tick} (MJ), {@code burn_time} (ticks per
 * bucket), optional {@code residue} (fluid stack produced per bucket burnt). A {@code #c:fuel} entry doesn't override
 * other entries ({@link #FUEL_MERGER}).</li>
 * <li>{@code data/<namespace>/data_maps/fluid/coolants.json}: {@code degrees_per_mb}.</li>
 * <li>{@code data/<namespace>/data_maps/item/solid_coolants.json}: {@code fluid}, the coolant one item melts into.</li>
 * </ul>
 * Distiller and heat exchanger recipes (1.12's refinery recipes, also from {@code BCEnergyRecipes}) are data maps too,
 * keyed by the input fluid:
 * <ul>
 * <li>{@code fluid/distillation.json}: {@code amount} (mB of input per cycle), {@code gas} and {@code liquid} (the two
 * outputs, as fluid stacks) and {@code power} (MJ per cycle).</li>
 * <li>{@code fluid/heatable.json} and {@code fluid/coolable.json}: {@code amount} (mB per step), optional
 * {@code result} (the fluid it turns into; none means it is used up, like water and lava), and {@code heat_from} and
 * {@code heat_to}.</li>
 * </ul> */
public final class BCFluidDataMaps {
    private BCFluidDataMaps() {}

    public record FuelData(double powerPerTick, int burnTime, Optional<FluidStack> residue) {
        public static final Codec<FuelData> CODEC = RecordCodecBuilder.create(i -> i.group(
            Codec.DOUBLE.fieldOf("power_per_tick").forGetter(FuelData::powerPerTick),
            ExtraCodecs.POSITIVE_INT.fieldOf("burn_time").forGetter(FuelData::burnTime),
            FluidStack.CODEC.optionalFieldOf("residue").forGetter(FuelData::residue)
        ).apply(i, FuelData::new));
    }

    public record CoolantData(float degreesPerMb) {
        public static final Codec<CoolantData> CODEC = RecordCodecBuilder.create(i -> i.group(
            Codec.FLOAT.fieldOf("degrees_per_mb").forGetter(CoolantData::degreesPerMb)
        ).apply(i, CoolantData::new));
    }

    public record SolidCoolantData(FluidStack fluid) {
        public static final Codec<SolidCoolantData> CODEC = RecordCodecBuilder.create(i -> i.group(
            FluidStack.CODEC.fieldOf("fluid").forGetter(SolidCoolantData::fluid)
        ).apply(i, SolidCoolantData::new));
    }

    public record DistillationData(int amount, FluidStack gas, FluidStack liquid, double power) {
        public static final Codec<DistillationData> CODEC = RecordCodecBuilder.create(i -> i.group(
            ExtraCodecs.POSITIVE_INT.fieldOf("amount").forGetter(DistillationData::amount),
            FluidStack.CODEC.fieldOf("gas").forGetter(DistillationData::gas),
            FluidStack.CODEC.fieldOf("liquid").forGetter(DistillationData::liquid),
            Codec.DOUBLE.fieldOf("power").forGetter(DistillationData::power)
        ).apply(i, DistillationData::new));
    }

    public record HeatExchangeData(int amount, Optional<FluidStack> result, int heatFrom, int heatTo) {
        public static final Codec<HeatExchangeData> CODEC = RecordCodecBuilder.create(i -> i.group(
            ExtraCodecs.POSITIVE_INT.fieldOf("amount").forGetter(HeatExchangeData::amount),
            FluidStack.CODEC.optionalFieldOf("result").forGetter(HeatExchangeData::result),
            Codec.INT.fieldOf("heat_from").forGetter(HeatExchangeData::heatFrom),
            Codec.INT.fieldOf("heat_to").forGetter(HeatExchangeData::heatTo)
        ).apply(i, HeatExchangeData::new));
    }

    /** {@code c:fuel}, which other mods fill with every fuel they make (diesel, gasoline, LPG and creosote alike). */
    private static final TagKey<Fluid> COMMON_FUEL = FluidTags.create(ResourceLocation.fromNamespaceAndPath("c", "fuel"));

    /** In the fuel data map, a {@code #c:fuel} entry never replaces a value a fluid already has (from {@code #c:diesel},
     * say), whichever order the entries load in: {@code c:fuel} is the fallback for fuels no other entry names. Every
     * other entry overrides earlier ones as usual, and {@code "replace": true} on an entry still overrides anything. */
    public static final DataMapValueMerger<Fluid, FuelData> FUEL_MERGER = (registry, first, firstValue, second,
        secondValue) -> second.left().filter(COMMON_FUEL::equals).isPresent() ? firstValue : secondValue;

    public static final DataMapType<Fluid, FuelData> FUELS = AdvancedDataMapType
        .builder(BuildCraftReborn.id("fuels"), Registries.FLUID, FuelData.CODEC)
        .synced(FuelData.CODEC, false)
        .merger(FUEL_MERGER)
        .build();

    public static final DataMapType<Fluid, CoolantData> COOLANTS = DataMapType
        .builder(BuildCraftReborn.id("coolants"), Registries.FLUID, CoolantData.CODEC)
        .synced(CoolantData.CODEC, false)
        .build();

    public static final DataMapType<Item, SolidCoolantData> SOLID_COOLANTS = DataMapType
        .builder(BuildCraftReborn.id("solid_coolants"), Registries.ITEM, SolidCoolantData.CODEC)
        .synced(SolidCoolantData.CODEC, false)
        .build();

    public static final DataMapType<Fluid, DistillationData> DISTILLATION = DataMapType
        .builder(BuildCraftReborn.id("distillation"), Registries.FLUID, DistillationData.CODEC)
        .synced(DistillationData.CODEC, false)
        .build();

    public static final DataMapType<Fluid, HeatExchangeData> HEATABLE = DataMapType
        .builder(BuildCraftReborn.id("heatable"), Registries.FLUID, HeatExchangeData.CODEC)
        .synced(HeatExchangeData.CODEC, false)
        .build();

    public static final DataMapType<Fluid, HeatExchangeData> COOLABLE = DataMapType
        .builder(BuildCraftReborn.id("coolable"), Registries.FLUID, HeatExchangeData.CODEC)
        .synced(HeatExchangeData.CODEC, false)
        .build();

    public static void register(RegisterDataMapTypesEvent event) {
        event.register(DISTILLATION);
        event.register(HEATABLE);
        event.register(COOLABLE);
        event.register(FUELS);
        event.register(COOLANTS);
        event.register(SOLID_COOLANTS);
    }
}
